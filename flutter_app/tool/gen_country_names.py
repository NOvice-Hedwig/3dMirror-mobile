"""
Generate lib/core/data/country_names.dart: Chinese and English names for every IsoCode that
phone_numbers_parser supports, taken from Unicode CLDR (via Babel). Dev-time only — the app
has no runtime dependency on this script or on Babel.

Usage (from flutter_app/):
  pip install babel
  python tool/gen_country_names.py <path to phone_numbers_parser>/lib/src/iso_codes/iso_code.dart

Re-run after upgrading phone_numbers_parser (new IsoCodes) or to pick up newer CLDR names.
"""

import re
import sys
from pathlib import Path

import babel
from babel import Locale
from babel.core import get_cldr_version

OUT = Path(__file__).resolve().parent.parent / "lib" / "core" / "data" / "country_names.dart"


def dart_str(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def main() -> None:
    iso_src = Path(sys.argv[1]).read_text(encoding="utf-8")
    enum_body = re.search(r"enum IsoCode\s*\{(.*?)\}", iso_src, re.S)
    if not enum_body:
        raise SystemExit("enum IsoCode not found — wrong file?")
    codes = re.findall(r"\b([A-Z]{2})\b", enum_body.group(1))   # last entry has no comma
    if len(codes) < 200:
        raise SystemExit(f"only {len(codes)} IsoCodes found — wrong file?")
    zh, en = Locale("zh"), Locale("en")
    missing = [c for c in codes if c not in zh.territories or c not in en.territories]
    if missing:
        raise SystemExit(f"CLDR has no name for: {missing}")

    lines = [
        "// GENERATED by tool/gen_country_names.py — do not edit by hand.",
        f"// Source: Unicode CLDR {get_cldr_version()} via Babel {babel.__version__};"
        f" {len(codes)} regions = phone_numbers_parser IsoCode.",
        "",
        "/// Country/region display names keyed by ISO 3166-1 alpha-2 code (IsoCode.name).",
        "const Map<String, ({String zh, String en})> kCountryNames = {",
    ]
    for c in codes:
        lines.append(f"  '{c}': (zh: {dart_str(zh.territories[c])}, en: {dart_str(en.territories[c])}),")
    lines.append("};")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(codes)} regions)")


if __name__ == "__main__":
    main()
